import assert from 'node:assert/strict';
import {build} from 'esbuild';
const calls=[],user={id:'11111111-1111-4111-8111-111111111111',email:'narrator@hotmail.com'};
const accessToken='fixture.'+Buffer.from(JSON.stringify({sub:user.id,exp:Math.floor(Date.now()/1000)+3600})).toString('base64url')+'.signature';
globalThis.location={origin:'https://storypress-preview.example.test'};
globalThis.fetch=async(input,init={})=>{
 const url=String(input),body=init.body?JSON.parse(init.body):undefined;calls.push({url,body});
 if(url==='/api/account')return Response.json({user:null,supabase:{url:'https://email-fixture.supabase.invalid',key:'fixture-public'},storage:true});
 if(url.includes('/auth/v1/otp'))return Response.json({});
 if(url.includes('/auth/v1/verify'))return body.token==='123456'?Response.json({access_token:accessToken,refresh_token:'fixture-refresh',token_type:'bearer',expires_in:3600,user}):Response.json({code:'otp_expired',msg:'Token has expired or is invalid'},{status:403});
 if(url.includes('/auth/v1/user'))return Response.json(user);
 if(url.includes('/auth/v1/logout'))return new Response(null,{status:204});
 throw new Error('Unexpected network request in fixture');
};
const result=await build({entryPoints:['lib/account-client.ts'],bundle:true,write:false,platform:'node',format:'esm'});
const client=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'));
const observed=[],account=await client.setupAccount(next=>observed.push(next));
await client.signIn('  Narrator@Hotmail.com ');
assert.deepEqual(calls.find(c=>c.url.includes('/auth/v1/otp')).body.email,'narrator@hotmail.com');
assert.equal(calls.find(c=>c.url.includes('/auth/v1/otp')).url.includes('redirect_to=https%3A%2F%2Fstorypress-preview.example.test%2F'),true,'Email links retain the app origin');
const before=calls.length;await assert.rejects(client.verifyEmailCode(user.email,'123'),/Enter the code/);assert.equal(calls.length,before,'Incomplete codes never reach the provider');
await assert.rejects(client.verifyEmailCode(user.email,'000000'),/expired|invalid/);
await client.verifyEmailCode(' Narrator@Hotmail.com ','123 456');
const verified=calls.filter(c=>c.url.includes('/auth/v1/verify')).at(-1).body;
assert.deepEqual({email:verified.email,token:verified.token,type:verified.type},{email:user.email,token:'123456',type:'email'});
assert.ok(observed.some(next=>next?.id===user.id),'Successful code verification updates the app account');
assert.equal((await client.accountHeaders()).Authorization,'Bearer '+accessToken,'Normal signed-in API calls use the new session');
account.dispose();await client.signOut();
console.log('Passed email-code requests, provider validation, code verification, auth session handoff and normalized Hotmail addresses. Provider mocked; no email sent.');
